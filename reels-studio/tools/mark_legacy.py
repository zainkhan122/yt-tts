#!/usr/bin/env python3
"""Mark briefs whose video already went out as LEGACY (config/legacy-briefs.json).

Source of truth: tracker/publications.json. A brief is legacy when any platform record is `sent` or
`published_manual` (it is live). `scheduled` and `uncertain` are NOT legacy: they still need the checks.
Legacy briefs keep lint, rules, motion and layout checks, but the new cloud-source checks (assets,
capture-pack release, cover) report NOTE instead of BLOCK, because a published video is never re-rendered
from its old brief without a new decision.

Usage: python3 tools/mark_legacy.py          # rewrite config/legacy-briefs.json
"""
import datetime as dt
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIVE_STATES = {"sent", "published_manual"}
OUT = ROOT / "config" / "legacy-briefs.json"


def compute(publications: dict) -> dict:
    live = {}
    for key, rec in publications.get("records", {}).items():
        vid, _, platform = key.partition(":")
        if rec.get("state") in LIVE_STATES:
            live.setdefault(vid, set()).add(platform)
    return {vid: sorted(p) for vid, p in sorted(live.items())}


def load_legacy() -> set:
    if not OUT.exists():
        return set()
    return set(json.loads(OUT.read_text(encoding="utf-8")).get("briefs", {}))


def main() -> int:
    pubs = json.loads((ROOT / "tracker" / "publications.json").read_text(encoding="utf-8"))
    briefs = compute(pubs)
    doc = {"_about": "Briefs whose video was sent or published. Generated by tools/mark_legacy.py from tracker/publications.json. Do not edit by hand.",
           "generated": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
           "briefs": briefs}
    OUT.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{len(briefs)} legacy brief(s) -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
